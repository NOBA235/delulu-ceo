import { PitchResponse } from "../validation/pitch-response";

export function formatPitch(pitch: PitchResponse): string {
  const startupPitchBody = pitch.investmentRationale
    ? `${pitch.startupConcept}\n${pitch.investmentRationale}`
    : pitch.startupConcept;

  return [
    "DELULU CEO",
    "Your worst decisions. Our next unicorn.",
    "",
    "🚀 STARTUP PITCH",
    pitch.startupName,
    startupPitchBody,
    "",
    "📰 FORBES HEADLINE",
    pitch.forbesHeadline,
    "",
    "📉 RISK ANALYSIS",
    pitch.riskAnalysis,
    "",
    "👔 CEO VERDICT",
    pitch.ceoVerdict,
    "",
    "Generated by Delulu CEO — Your worst decisions. Our next unicorn.",
  ].join("\n");
}
